// GL Work (docs/fork/changes/glwork-mobile-brand.md): adopt the UIScene life cycle. iOS 27 ends an app
// built with the iOS 27 SDK at launch when it still sets up its window in the app delegate
// (UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption), which Expo's template does.
// The window and React Native now start from a scene delegate; URLs reach RCTLinkingManager from it.
const {
  IOSConfig,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject
} = require('expo/config-plugins')
const fs = require('node:fs')
const path = require('node:path')

const SCENE_DELEGATE = `import UIKit
import React

/// Generated by plugins/glwork-scene-lifecycle.js.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
      let appDelegate = UIApplication.shared.delegate as? AppDelegate,
      let factory = appDelegate.reactNativeFactory
    else { return }
    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[.url] = url
    }
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)
    if let activity = connectionOptions.userActivities.first {
      self.scene(scene, continue: activity)
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    for context in URLContexts {
      _ = RCTLinkingManager.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = RCTLinkingManager.application(
      UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`

// The template's window set-up in application(_:didFinishLaunchingWithOptions:).
const APP_DELEGATE_WINDOW =
  /#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\([\s\S]*?\)\n#endif\n/

function withSceneManifest(config) {
  return withInfoPlist(config, (mod) => {
    mod.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate'
          }
        ]
      }
    }
    return mod
  })
}

function withSceneDelegateSources(config) {
  return withDangerousMod(config, [
    'ios',
    (mod) => {
      const dir = path.join(mod.modRequest.platformProjectRoot, mod.modRequest.projectName)
      const appDelegatePath = path.join(dir, 'AppDelegate.swift')
      const appDelegate = fs.readFileSync(appDelegatePath, 'utf8')
      if (!APP_DELEGATE_WINDOW.test(appDelegate)) {
        throw new Error(
          'glwork-scene-lifecycle: AppDelegate.swift no longer sets up the window as expected'
        )
      }
      fs.writeFileSync(
        appDelegatePath,
        appDelegate.replace(
          APP_DELEGATE_WINDOW,
          '    // The window starts in SceneDelegate (UIScene life cycle).\n'
        )
      )
      fs.writeFileSync(path.join(dir, 'SceneDelegate.swift'), SCENE_DELEGATE)
      return mod
    }
  ])
}

function withSceneDelegateInProject(config) {
  return withXcodeProject(config, (mod) => {
    const name = mod.modRequest.projectName
    const filepath = `${name}/SceneDelegate.swift`
    if (!mod.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: name,
        project: mod.modResults
      })
    }
    return mod
  })
}

module.exports = function withGlWorkSceneLifecycle(config) {
  return withSceneDelegateInProject(withSceneDelegateSources(withSceneManifest(config)))
}
